export function t(lang: AppLanguage, key: string): string {
  const dict = TRANSLATIONS[lang] ?? EN;
  return dict[key] ?? EN[key] ?? key;
}

export function tCategory(lang: AppLanguage, cat: CategoryId): string {
  return t(lang, `cat_${cat}`);
}

export function tQueueMode(lang: AppLanguage, mode: QueueMode): string {
  if (mode === 'sequential') return t(lang, 'queueSequential');
  if (mode === 'parallel-equal') return t(lang, 'queueEqual');
  return t(lang, 'queueParallel');
}

